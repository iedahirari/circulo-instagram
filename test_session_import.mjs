import assert from 'node:assert/strict';
import {parseExport,validateProfile,matchesProfile,mergeCollectedProfile,sameSnapshotLists} from './core.mjs';
const row={id:'12',username:'alice',fullName:'Alice',isVerified:true};
const data={format:'circulo-session-v1',account:'ieda',capturedAt:'2026-11-05T15:00:00.000Z',complete:true,counts:{followers:1,following:1},followers:[row],following:[row]};
const parse=d=>parseExport(new File([JSON.stringify(d)],'circulo-consulta.json'));
const result=await parse(data);
assert.deepEqual(result.followers,['alice']);assert.equal(result.profiles.length,1);
assert.equal(validateProfile(result.profiles[0]).isVerified,true);
assert.equal(validateProfile(result.profiles[0]).isPrivate,undefined);
const withPhoto=await parse({...data,followers:[{...row,photo:'data:image/jpeg;base64,/9j/'}],following:[{...row,photo:'data:image/jpeg;base64,/9j/'}]});
assert.equal(withPhoto.profiles[0].photo,'data:image/jpeg;base64,/9j/');
const saved={...result.profiles[0],category:'artist',categorySource:'manual',photo:null};
assert.equal(mergeCollectedProfile(withPhoto.profiles[0],saved).photo,'data:image/jpeg;base64,/9j/');
assert.equal(mergeCollectedProfile(withPhoto.profiles[0],saved).category,'artist');
assert.equal(mergeCollectedProfile(withPhoto.profiles[0],{...saved,photo:'data:image/jpeg;base64,YQ=='}).photo,'data:image/jpeg;base64,YQ==');
assert.throws(()=>mergeCollectedProfile(withPhoto.profiles[0],{...saved,account:'other'}));
await assert.rejects(parse({...data,followers:[{...row,photo:'https://example.com/a.jpg'}]}));
const snapshot={id:'1',account:'ieda',date:'2026-11-06',source:'test.json',followers:['alice','bob'],following:['alice']};
assert.equal(sameSnapshotLists(snapshot,{...snapshot,id:'2',followers:['bob','alice']}),true);
assert.equal(sameSnapshotLists(snapshot,{...snapshot,followers:['alice']}),false);
assert.equal(sameSnapshotLists(snapshot,{...snapshot,account:'other'}),false);
const privateData=await parse({...data,followers:[{...row,isPrivate:true}],following:[{...row,isPrivate:true}]});
assert.equal(validateProfile(privateData.profiles[0]).isPrivate,true);
await assert.rejects(parse({...data,followers:[{...row,isPrivate:'yes'}]}));
const profile={fullName:'Cláudia da Silva',isVerified:true,isPrivate:false};
assert.equal(matchesProfile('claudia',profile,'  CLAUDIA DA SILVA  ','yes','no'),true);
assert.equal(matchesProfile('claudia',profile,'@CLAUDIA','all','all'),true);
assert.equal(matchesProfile('claudia',profile,'','no'),false);
assert.equal(matchesProfile('claudia',undefined,'','unknown','unknown'),true);
assert.equal(matchesProfile('claudia',undefined,'','no','no'),false);
assert.equal(matchesProfile('claudia',profile,'outro'),false);
await assert.rejects(parse({...data,complete:false}));
await assert.rejects(parse({...data,counts:{followers:2,following:1}}));
await assert.rejects(parse({...data,followers:[{...row,id:undefined}]}));
await assert.rejects(parse({...data,following:[{...row,username:'bob'}]}));
await assert.rejects(parse({...data,account:'../ieda'}));
await assert.rejects(parse({...data,followers:[{...row,isVerified:'true'}]}));
console.log('Importação da sessão e metadados verificados.');
